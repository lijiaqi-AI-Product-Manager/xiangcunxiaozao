-- 菜品小图（点单页每行左边 64×64 的小格子 / 详情页标题上方那条图）
--
-- 背景：老板上传一张菜品图，顾客端两处要用同一张内容：
--   ① 点单页每道菜左边的小方格（以前是「首字 + 淡墨痕」的占位）
--   ② 点进这道菜后，菜名上方的空白大图位（以前也是空的，等实物图）
-- 两处必须**同一张图**：老板传一次，两处都有；换图时两处一起换。
--
-- 为什么小图要单独存一列、还要单独传一份文件：
--   小格子最大 64px（窄屏 54px），3 倍屏也就 192px。把 1600px 的大图塞进 64px 格子里，
--   手机要白下载 200～300KB、还得自己做缩放；一百多道菜全算上就是好几 MB 流量。
--   所以上传时浏览器顺手压一张 200px 的小图（十几 KB），两处各用各的：
--   大图位用 image_closed，小格子用 image_thumb；没有小图就退回大图（老数据、老客户端照旧能用）。
--
-- 为空时表示「没单独传小图，用大图」——不留空字符串，统一用 NULL 表达「没有」。
ALTER TABLE dish_overrides ADD COLUMN image_thumb TEXT;
